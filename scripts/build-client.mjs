/**
 * Build the browser half into the single artifact the Client module table
 * serves: `client.js` with a `window.__ModuleLoader__.load({...})` wrapper.
 *
 * React itself stays external (`require('react')` from the browser module
 * table), while the chart math from d3 is bundled inline. CSS is collected into
 * one string at build time so the runtime injects exactly one stylesheet as a
 * plugin-owned effect.
 */

import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dev = process.argv.includes('--dev')

const CSS_FILES = [
  'src/client/styles/base.css',
  'src/client/styles/sections.css',
  'src/client/styles/charts.css',
]

const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const css = (await Promise.all(CSS_FILES.map((file) => readFile(path.join(root, file), 'utf8')))).join('\n')

const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client/index.jsx'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime', 'react-dom'],
  minify: !dev,
  legalComments: 'none',
  define: {
    __STATS_CSS__: JSON.stringify(css),
  },
  loader: {
    '.js': 'jsx',
  },
  logLevel: 'warning',
})

const code = result.outputFiles[0].text
const banner = [
  `/* dsh-session-dashboard v${pkg.version} — generated by scripts/build-client.mjs. Do not edit directly. */`,
].join('\n')
const output = `${banner}\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(pkg.name)},\n  factory(require) {\n    var module = { exports: {} };\n    var exports = module.exports;\n${code}\n    return module.exports;\n  },\n});\n`

await writeFile(path.join(root, 'client.js'), output)
const bytes = Buffer.byteLength(output)
console.log(`built client.js (${(bytes / 1024).toFixed(1)} KiB, minify=${!dev})`)
